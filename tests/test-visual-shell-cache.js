'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync(require.resolve('../index.html'),'utf8');
const worker=fs.readFileSync(require.resolve('../sw.js'),'utf8');
const designSystem=fs.readFileSync(require.resolve('../design-system.css'),'utf8');
assert.match(html,/identity-ui\.css[\s\S]*design-system\.css/u,'design system loads after identity component styles');
assert.match(worker,/\/design-system\.css/u,'offline app shell precaches the design system');
assert.match(worker,/\/app\.js\?v=0140\.2/u,'offline app shell uses the same application revision as HTML');
assert.match(html,/app\.js\?v=0140\.2/u,'HTML and app shell revisions are aligned');
assert.ok(worker.includes('`${CACHE_PREFIX}v17`'),'shell cache advances when its asset manifest changes');
assert.match(worker,/styles\.css\?v=0140\.2/u,'corrected mobile styles use a new cache key');
assert.match(worker,/design-system\.css\?v=0140\.2/u,'corrected navigation styles use a new cache key');
assert.match(worker,/Promise\.allSettled\(APP_SHELL\.map/u,'one unavailable optional asset cannot block installing all updated app assets');
assert.match(worker,/OPTIONAL_ASSETS\.has\(APP_SHELL\[index\]\)/u,'only explicitly optional cartography assets may be absent during shell installation');
assert.match(html,/vendor\/maplibre\/rotamoto-map-runtime\.js\?v=0140\.2/u,'HTML loads the current map runtime from the static-allowlisted vendor subdirectory');
assert.match(worker,/vendor\/maplibre\/rotamoto-map-runtime\.js\?v=0140\.2/u,'offline shell caches the current map runtime');
assert.match(worker,/maplibre\/maplibre-gl-worker\.js\?v=0139\.1/u,'offline shell caches the local map worker');
assert.match(designSystem,/@media\(max-width:560px\)\{\.main\{padding:0 12px calc\(104px \+ env\(safe-area-inset-bottom\)\)/u,
  'mobile content begins below the real in-flow header and keeps clearance for the bottom navigation');
console.log('Restaurant visual foundation offline shell contract: PASS');
