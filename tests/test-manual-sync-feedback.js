'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('../app.js'), 'utf8');
const match = source.match(/function classifyManualSyncResult\([^\n]+/u);
assert.ok(match, 'manual sync feedback classifier exists');
const context = {};
vm.runInNewContext(`${match[0]}\nthis.classify = classifyManualSyncResult;`, context);
const classify = context.classify;
const noSession = classify({hasSession:false});
assert.equal(noSession.state, 'attention');
assert.match(noSession.detail, /dados locais continuam disponíveis/u);
const offline = classify({error:new Error('OFFLINE'),online:false});
assert.equal(offline.state, 'offline');
assert.match(offline.detail, /continuam salvas/u);
const expired = classify({error:Object.assign(new Error('UNAUTHENTICATED'),{status:401})});
assert.equal(expired.label, 'Sessão encerrada');
const denied = classify({error:new Error('SYNC_PERMISSION_REQUIRED')});
assert.equal(denied.label, 'Sincronização não habilitada');
assert.match(denied.detail, /administrador da empresa/u);
const serverFailure = classify({error:Object.assign(new Error('HTTP'),{status:503})});
assert.equal(serverFailure.state, 'retry');
assert.doesNotMatch(serverFailure.detail, /confirmou/u);
const rateLimited = classify({error:Object.assign(new Error('HTTP'),{status:429})});
assert.equal(rateLimited.state, 'retry');
const pending = classify({result:{operationResults:[{status:'accepted'}]},after:{pending:1}});
assert.equal(pending.label, 'Sincronização pendente');
assert.match(pending.detail, /aguardam confirmação/u);
assert.doesNotMatch(pending.detail, /Atualização concluída/u);
const unchanged = classify({result:{operationResults:[],pulled:0},after:{pending:0}});
assert.equal(unchanged.label, 'Nenhuma novidade');
const complete = classify({result:{operationResults:[{status:'accepted'}],pulled:2},after:{pending:0}});
assert.equal(complete.label, 'Atualização concluída');
assert.match(complete.detail, /Servidor confirmou 1 resultado/u);
const conflicts = classify({after:{conflicts:1,rejected:0,pending:0}});
assert.equal(conflicts.state, 'attention');
assert.match(conflicts.label, /precisa de atenção/u);
assert.match(source, /syncNowButton\.onclick=\(\)=>runManualSync\(syncNowButton\)/u);
assert.match(source, /hasSyncPushPermission\(session\)\)throw new Error\('SYNC_PERMISSION_REQUIRED'\)/u,
  'client must reject unauthorized sync before registering an installation or sending data');
assert.match(source, /button\.setAttribute\('aria-busy'/u);
assert.match(source, /data-app-toast/u, 'toast surface is reused instead of stacking duplicate notifications');
assert.match(source, /d\.setAttribute\('role',type==='error'\?'alert':'status'\)/u,
  'toast severity is announced with the correct accessible role');
assert.match(source, /d\.replaceChildren\(title,detail\)/u, 'toast content is updated safely without HTML injection');
console.log('manual sync feedback: all result and failure states PASS');
