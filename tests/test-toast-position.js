'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('app.js', 'utf8');
const match = source.match(/function toastOffsetForNavigation\(nav,viewportHeight,display,gap=12\)\{[^\n]+\}/u);
assert.ok(match, 'toast offset is derived from the live navigation geometry');
const context = {};
vm.runInNewContext(`${match[0]}\nthis.offset=toastOffsetForNavigation;`, context);
const nav = top => ({ getBoundingClientRect: () => ({ top, height: 68 }) });
assert.equal(context.offset(nav(632), 700, 'flex'), 80, 'mobile offset clears the visible bottom navigation and adds a gap');
assert.equal(context.offset(nav(956), 1024, 'grid'), 80, 'tablet offset follows the actual navigation height');
assert.equal(context.offset(null, 900, 'none'), 12, 'desktop without bottom navigation keeps a small margin');
assert.equal(context.offset(nav(600), 700, 'none'), 12, 'hidden navigation does not reserve phantom space');
assert.equal(context.offset(nav(700), 700, 'flex'), 12, 'offscreen/zero-height navigation falls back safely');
assert.match(source, /syncNavActive\(\);syncToastOffset\(\)/u, 'navigation rerenders recalculate toast placement');
const css = fs.readFileSync('styles.css', 'utf8') + fs.readFileSync('design-system.css', 'utf8');
assert.match(css, /\.toast\{[^}]*z-index:1700;pointer-events:none;/u, 'informational toast paints above navigation without intercepting taps');
assert.doesNotMatch(css, /\.toast[^}]*bottom:calc\((?:var\(--mobile-bottom-space|7[248]px)/u, 'fixed guessed mobile offsets are removed');
assert.match(css, /bottom:var\(--app-toast-offset,18px\)/u, 'all responsive toast layouts use measured clearance');
console.log('Toast position against live bottom navigation: PASS');
