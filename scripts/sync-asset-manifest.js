'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(__dirname, 'asset-manifest.config.json'), 'utf8'));
const indexPath = path.join(root, 'index.html');
const indexSource = fs.readFileSync(indexPath, 'utf8');
const virtualFiles = new Map();
const digest = value => crypto.createHash('sha256').update(value).digest('hex').slice(0, 16);

function localFile(assetPath) {
  const pathname = new URL(assetPath, 'https://assets.invalid').pathname;
  const file = path.resolve(root, `.${pathname}`);
  if (!file.startsWith(`${root}${path.sep}`) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
    throw new Error(`asset local ausente ou fora do projeto: ${pathname}`);
  }
  return file;
}

function fileBytes(file) { return virtualFiles.get(file) ?? fs.readFileSync(file); }
function versionedUrl(assetPath) {
  const url = new URL(assetPath, 'https://assets.invalid');
  if (url.origin !== 'https://assets.invalid') return assetPath;
  const file = localFile(url.pathname);
  return `${assetPath.split('?')[0]}?v=${digest(fileBytes(file))}`;
}

for (const referenceFile of config.referenceFiles || []) {
  const file = localFile(referenceFile);
  let source = fs.readFileSync(file, 'utf8');
  source = source.replace(/((?:\.\/|\.\.\/|\/)?[\w./-]+\.(?:js|css|svg|png|wasm|json|gz))\?v=[^\s"'`)]+/gu,
    (whole, assetPath) => {
      try { return versionedUrl(assetPath); } catch (_) { return whole; }
    });
  virtualFiles.set(file, Buffer.from(source));
}

const tagPattern = /<(?:script|link)\b[^>]*>/giu;
let nextIndex = indexSource.replace(tagPattern, tag => {
  const name = /<script\b/iu.test(tag) ? 'src' : 'href';
  return tag.replace(new RegExp(`\\b${name}=(['"])([^'"]+)\\1`, 'iu'), (whole, quote, value) => {
    try {
      const url = new URL(value, 'https://assets.invalid');
      if (url.origin !== 'https://assets.invalid') return whole;
      return `${name}=${quote}${versionedUrl(value)}${quote}`;
    } catch (error) { throw new Error(`não foi possível versionar asset da página (${name}): ${error.message}`); }
  });
});

function canonical(assetPath) {
  const url = new URL(assetPath, 'https://assets.invalid/');
  if (url.origin !== 'https://assets.invalid') throw new Error(`asset offline externo não suportado: ${assetPath}`);
  return `./${url.pathname.slice(1)}${url.search}`;
}

const extras = (config.extraAssets || []).map(versionedUrl);
const taggedAssets = [...nextIndex.matchAll(tagPattern)].flatMap(([tag]) => {
  const name = /<script\b/iu.test(tag) ? 'src' : 'href';
  const match = new RegExp(`\\b${name}=(['"])([^'"]+)\\1`, 'iu').exec(tag);
  if (!match) return [];
  try { return [canonical(match[2])]; } catch (_) { return []; }
});
const assets = [...new Set(['./', './index.html', './asset-manifest.js', ...taggedAssets, ...extras])];
const optional = [...new Set((config.optionalAssets || []).map(assetPath => canonical(versionedUrl(assetPath))) )];
for (const asset of optional) if (!assets.includes(asset)) assets.push(asset);
virtualFiles.set(indexPath, Buffer.from(nextIndex));

const assetDigests = assets.filter(asset => asset !== './' && asset !== './asset-manifest.js').map(asset => {
  const url = new URL(asset, 'https://assets.invalid/');
  const file = localFile(url.pathname);
  return [asset, digest(fileBytes(file))];
});
assetDigests.push(['/sw.js', digest(fs.readFileSync(path.join(root, 'sw.js')))]);
const buildId = digest(JSON.stringify(assetDigests));
const manifest = `/* Generated by scripts/sync-asset-manifest.js; do not edit. */\nself.RotaMotoAssetManifest = Object.freeze(${JSON.stringify({
  appId: config.appId, cachePrefix: config.cachePrefix, cacheName: `${config.cachePrefix}${buildId}`, assets, optional
}, null, 2)});\n`;

function writeOrCheck(file, expected) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== expected) throw new Error(`${path.relative(root, file)} está desatualizado; execute npm run assets:sync.`);
  } else if (current !== expected) fs.writeFileSync(file, expected);
}

for (const [file, bytes] of virtualFiles) writeOrCheck(file, bytes.toString('utf8'));
writeOrCheck(indexPath, nextIndex);
writeOrCheck(path.join(root, 'asset-manifest.js'), manifest);
if (!process.argv.includes('--check')) process.stdout.write(`asset manifest atualizado: ${config.appId} ${buildId}\n`);
